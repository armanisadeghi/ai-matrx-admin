import { session, chromium, go, SHOT } from "./tp3-lib.mjs";
const TABLE = process.argv[3] ?? "b79ba573-fb65-46f9-be54-e37d11ee4206";
const browser = await chromium.launch({ headless: true });
const { origin, state } = await session(process.argv[2] ?? "admin", 1440, 900, browser);
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: state });
const page = await ctx.newPage();
const logs = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) logs.push(m.type() + ": " + m.text().slice(0, 600)); });
page.on("pageerror", (e) => logs.push("pageerror: " + String(e).slice(0, 600)));
page.on("response", async (r) => { if (r.url().includes("rpc/record_write")) { logs.push("REQ " + (r.request().postData() ?? "").slice(0, 1500)); logs.push("RES " + (await r.text().catch(() => "?")).slice(0, 1500)); } if (r.status() >= 400) logs.push(`HTTP ${r.status()} ${r.request().method()} ${r.url().slice(0, 200)}`); });
await go(page, `${origin}/data/${TABLE}`, 12000);
await page.screenshot({ path: "/private/tmp/claude-501/-Users-armanisadeghi-code/4aca9d01-f3c0-4271-be17-2f948446dfb3/scratchpad/t1.png" });
console.log("before dup logs:", JSON.stringify(logs, null, 1));
logs.length = 0;
await page.getByRole("button", { name: "Close" }).first().click({ timeout: 3000 }).catch(() => {});
await page.waitForTimeout(500);
logs.length = 0;
await page.screenshot({ path: SHOT + "t1b.png" });
await page.locator("[data-records-duplicate]").first().evaluate((e) => e.click());
await page.waitForTimeout(6000);
await page.screenshot({ path: "/private/tmp/claude-501/-Users-armanisadeghi-code/4aca9d01-f3c0-4271-be17-2f948446dfb3/scratchpad/t2.png" });
console.log("after dup logs:", JSON.stringify(logs, null, 1));
console.log((await page.innerText("body")).slice(0,200));
await page.getByText(/^\s*1\s*error/).first().click({ force: true, timeout: 5000 }).catch((e) => console.log("badge click failed", String(e).slice(0,100)));
await page.waitForTimeout(2500);
await page.screenshot({ path: SHOT + "t3.png" });
console.log("PANEL:", (await page.locator("[role=dialog], [data-error-inspector]").allInnerTexts()).join("\n---\n").slice(0, 3500));
await browser.close();
