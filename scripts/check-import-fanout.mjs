// THE FRAGMENTATION LAW, enforced (code-splitting skill, rule 3).
//
// Every distinct runtime `import()` target is its own lazily loaded chunk group, and the build pays
// for each one in memory and compile time on every release. Measured 2026-10-16: a generated map of
// 263 per-surface `import()`s cost +8.9 GB peak build memory (49.2 -> 40.3 GB) and ~540 server chunks;
// in 2026-10 an icon package's 2,118-entry per-icon map doubled the build. A set of things that load
// together gets ONE lazy module (or a few groups), never one import() per item.
//
// Fails when one source file has more than MAX_TARGETS distinct RUNTIME import() targets
// (`await import(…)`, `() => import(…)`, `import(…).then`). Type positions (`import("x").Type`,
// `typeof import("x")`) are not chunks and are not counted.
//
// THE HOST-ONLY RULE (same law, the reach half). A sanctioned fan-out is ONE lazily loaded module
// only if nothing but its host reaches it statically. HOST_ONLY lists, per guarded module, the only
// files allowed to import it with a STATIC edge (`import … from`, `export … from`, bare `import`;
// `import type` / `export type` erase and are ignored). Checking every direct importer is an exact
// reachability proof by induction: the overlay render map is reached only from OverlayWorldHost,
// which is reached only from app/DeferredOverlayWorld.tsx, which has NO static importer (one
// next/dynamic edge). Incident 2026-10-17: a `render: () => import()` on every overlay definition
// put ~220 window subtrees behind ~450 opener importers; lab.aimatrx.com's build OOM-killed.
// Usage: node scripts/check-import-fanout.mjs [--self-test]
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { posix, resolve } from "node:path";

export const MAX_TARGETS = 20;
// Sanctioned fan-outs. Empty since overlays moved to features/overlays/definitions (each definition
