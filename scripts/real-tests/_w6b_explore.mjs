import { createRequire } from "node:module";
import { mintSessionCookies, frontendEnv } from "./session-cookies.mjs";
import { markBrowserAgentTraffic } from "../lib/agent-traffic.mjs";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const { createClient } = require("@supabase/supabase-js");
const out = process.argv[2];
const env = frontendEnv();
const s = await mintSessionCookies("admin@admin.com");
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY);
const { error: e1 } = await sb.auth.signInWithPassword({ email: env.AI_ADMIN_USERNAME, password: env.AI_ADMIN_PASSWORD });
if (e1) throw e1;
const note = { id: process.argv[3] }; const error = null;
if (error) throw error;
console.log("note", note.id);
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, serviceWorkers: "block" });
await markBrowserAgentTraffic(ctx, "w6b-explore", "https://www.aimatrx.com");
await ctx.addCookies(s.cookies);
const page = await ctx.newPage();
await page.goto(`https://www.aimatrx.com/notes/${note.id}`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(12000);
await page.screenshot({ path: `${out}/1-page.png` });
const labels = await page.evaluate(() => Array.from(document.querySelectorAll("button[aria-label],[role=button][aria-label]")).map(b => b.getAttribute("aria-label")).filter(Boolean));
console.log("ARIA", JSON.stringify([...new Set(labels)]));
const pc = (sel, txt) => page.evaluate(([sel, txt]) => { const el = Array.from(document.querySelectorAll(sel)).find(e => !txt || (e.textContent||e.getAttribute("aria-label")||"").trim().startsWith(txt)); if (!el) return false; for (const t of ["pointerdown","mousedown","pointerup","mouseup","click"]) el.dispatchEvent(new (t.startsWith("pointer")?PointerEvent:MouseEvent)(t,{bubbles:true,cancelable:true})); return true; }, [sel, txt]);
await pc('[aria-label="Open Side Chat"]'); await page.waitForTimeout(6000);
await page.locator('[aria-label^="Agent:"]').first().click();
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/6-picker.png` });
console.log("POPPER", await page.evaluate(() => Array.from(document.querySelectorAll("[data-radix-popper-content-wrapper],[role=dialog],[role=listbox]")).map(w=>w.tagName+"#"+(w.getAttribute("role")||"")+": "+(w.innerText||"").replace(/\s+/g," ").slice(0,700)).join(" || ")));
console.log("INPUTS", await page.evaluate(() => Array.from(document.querySelectorAll("input")).filter(i=>i.getClientRects().length).map(i=>i.placeholder).join(" | ")));
await browser.close();
console.log("NOTE_ID", note.id);
