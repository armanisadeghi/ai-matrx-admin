import { session, chromium } from "./tp3-lib.mjs";
const browser = await chromium.launch({ headless: true });
const seat = process.argv[2] ?? "admin";
const { origin, state } = await session(seat, 1440, 900, browser);
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: state });
const page = await ctx.newPage();
await page.goto(origin + "/data", { timeout: 240_000 });
await page.waitForTimeout(15000);
console.log(page.url());
console.log((await page.innerText("body")).slice(0, 1500));
const links = await page.$$eval("a", (as) => as.map((a) => [a.textContent?.trim().slice(0, 40), a.getAttribute("href")]).filter((x) => /data/.test(x[1] ?? "")));
console.log(JSON.stringify(links.slice(0, 40)));
await browser.close();
