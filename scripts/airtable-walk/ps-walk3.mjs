import { start, open, out } from "./lib.mjs";
const TABLE = process.env.TABLE; const SHOTS = process.env.SHOTS; const TO = process.env.TO ?? "Text";
const { browser, page } = await start();
await open(page, TABLE);
await page.getByText("Mix and master").first().waitFor({ timeout: 180000 });
await page.waitForTimeout(2000);
await page.getByText("Lead", { exact: true }).first().click({ button: "right" });
await page.getByText("Column settings…").click();
await page.waitForTimeout(2000);
await page.getByLabel("Change what this column holds").click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${SHOTS}/05-${TO}-options.png` });
await page.getByRole("option", { name: TO, exact: true }).click();
await page.waitForTimeout(4000);
out("preview:", await page.locator("[data-records-retype-preview]").innerText().catch(() => "NO PREVIEW"));
await page.screenshot({ path: `${SHOTS}/06-${TO}-preview.png` });
await page.locator("[data-records-retype-go]").click();
await page.waitForTimeout(6000);
out("done:", await page.locator("[data-records-retype-done]").innerText().catch(() => "NO DONE"));
await page.screenshot({ path: `${SHOTS}/07-${TO}-done.png` });
await page.keyboard.press("Escape");
await page.waitForTimeout(1500);
await page.reload({ waitUntil: "domcontentloaded" });
await page.getByText("Mix and master").first().waitFor({ timeout: 180000 });
await page.waitForTimeout(4000);
await page.screenshot({ path: `${SHOTS}/08-${TO}-grid.png` });
const body = await page.locator("body").innerText();
out("uuid on screen:", /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i.test(body));
out("grid rows:", (await page.locator("[role=row]").allInnerTexts().catch(() => [])).slice(0, 6).join(" | ").replace(/\n/g, " ~ "));
await browser.close();
