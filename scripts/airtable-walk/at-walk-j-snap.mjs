import { open, say, ORIGIN } from "./at-walk-h-lib.mjs";
const home = process.env.HOME_ID;
const { browser, page, who, shot } = await open(false);
say("who", who);
const seen = new Set();
const poll = setInterval(async () => { try { const t = await page.evaluate(() => (document.querySelector('[role=dialog]')?.innerText ?? "").replace(/\s+/g, " ")); for (const m of t.matchAll(/[^.]*(Copying|Starting|Taking|Restoring|snapshot|of \d+ rows?)[^.]*/gi)) seen.add(m[0].trim().slice(0, 120)); } catch {} }, 500);
await page.goto(`${ORIGIN}/data/bases/${home}`, { waitUntil: "domcontentloaded", timeout: 240000 });
await page.waitForSelector(`[data-base-page="${home}"]`, { timeout: 240000 });
await page.locator("[data-base-snapshots]").click();
await page.getByLabel("Snapshot label").fill("ATWJ before").catch(() => {});
const t0 = Date.now();
await page.locator("[data-snapshot-take]").click();
await page.waitForSelector("[data-snapshot]", { timeout: 500000 }).catch(() => say("no snapshot row"));
say("snapshot took s", Math.round((Date.now() - t0) / 1000)); say("dialog lines seen during snapshot", [...seen]);
await shot("j4-snapshot");
seen.clear();
const t1 = Date.now();
await page.locator("[data-snapshot-restore]").first().click();
await page.waitForURL((u) => /\/data\/bases\/[0-9a-f-]{36}/.test(u.pathname) && !u.pathname.endsWith(home), { timeout: 500000 }).catch(() => say("no navigation to restored base"));
say("restore took s", Math.round((Date.now() - t1) / 1000)); say("lines seen during restore", [...seen]);
say("restored url", page.url());
await page.waitForSelector("[data-base-page]", { timeout: 120000 }).catch(() => {});
say("restored name", await page.locator("[data-base-name]").innerText().catch(() => "?"));
say("restored tables", await page.locator("[data-base-table]").allInnerTexts().catch(() => []));
clearInterval(poll); await browser.close();
