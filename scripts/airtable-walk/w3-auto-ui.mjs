import { start, open, T, out } from "./lib.mjs";
import { store } from "./store.mjs";
const member = process.argv[2] === "member";
const { browser, page, who } = await start(member);
out("who", who);
await open(page, T.events);
await page.getByRole("button", { name: "Table menu" }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: "/tmp/airtable-walk/a2.png" });
const items = await page.$$eval("[role=menuitem],[role=menu] button", (bs) => bs.map((b) => (b.textContent || "").trim()).filter(Boolean));
out(JSON.stringify(items));
await page.getByText("Built on it").first().hover().catch(() => {});
await page.getByText("Built on it").first().click().catch(() => {});
await page.waitForTimeout(400);
await page.getByRole("menuitem", { name: /Automations/ }).first().click();
await page.waitForTimeout(2500);
await page.screenshot({ path: "/tmp/airtable-walk/a3.png" });
const dlg = page.getByRole("dialog");
out("panel text:", (await dlg.innerText()).replace(/\n/g, " | ").slice(0, 500));
const sw = page.getByRole("switch", { name: "Automation on" });
out("switch count", await sw.count(), "checked", await sw.first().isChecked().catch(() => null));
await sw.first().click(); await page.waitForTimeout(1500);
out("after click checked", await sw.first().isChecked());
await page.getByRole("button", { name: "Runs" }).first().click(); await page.waitForTimeout(1500);
out("runs:", (await page.getByTestId("spaces-automation-runs").innerText().catch(() => "NONE")).replace(/\n/g, " | "));
await page.screenshot({ path: "/tmp/airtable-walk/a4.png" });
await page.getByRole("button", { name: "New automation" }).first().click().catch(() => out("no New automation button"));
await page.waitForTimeout(800);
out("editor words:", (await dlg.innerText()).match(/Page|Record|Property|Field/g)?.join(","));
await page.screenshot({ path: "/tmp/airtable-walk/a5.png" });
// reload and see switch persisted
await browser.close();
