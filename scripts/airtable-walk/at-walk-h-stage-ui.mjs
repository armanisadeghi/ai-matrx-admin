import { open, gotoTable, say } from "./at-walk-h-lib.mjs";
const [, , T, MEMBER] = process.argv;
const tag = MEMBER === "member" ? "member" : "admin";
const { browser, page, who, shot } = await open(MEMBER === "member");
await gotoTable(page, T);
await page.getByRole("button", { name: "Table menu" }).first().click();
await page.locator("[role^=menuitem]").filter({ hasText: /^Settings/ }).first().click();
await page.waitForTimeout(6000);
const d = page.locator("body");
const sec = d.getByText("Rules for entering a stage");
say("section", await sec.count());
await sec.first().scrollIntoViewIfNeeded().catch(() => {});
await shot(`stage-${tag}-1`);
say("TXT", (await d.innerText()).replace(/\n+/g, " | ").match(/Rules for entering a stage.{0,500}/)?.[0]);
const add = d.getByRole("button", { name: "Add a rule" });
say("add count", await add.count(), "disabled", await add.first().isDisabled().catch(() => null));
if (await add.count() && MEMBER !== "member") {
  await d.getByRole("button", { name: "Stage", exact: true }).last().click(); await page.locator("[role^=menuitem],[role=option]").filter({ hasText: /^Done/ }).first().click(); await page.waitForTimeout(800);
  await add.first().click();
  await page.waitForTimeout(1000);
  await d.getByLabel("Rule name").fill("ATWH Done needs a note");
  await page.getByRole("textbox", { name: "What it says" }).scrollIntoViewIfNeeded(); await shot(`stage-${tag}-2a`);
  say("EDITOR", (await d.innerText()).replace(/\n+/g, " | ").match(/Rules for entering.{0,700}/)?.[0]);
  say("clauses", await d.locator("[data-testid=stage-rule-clause-in-words] *").evaluateAll((e) => e.slice(0, 12).map((x) => x.tagName + ":" + (x.getAttribute("aria-label") || x.innerText).slice(0, 30))));
  await d.getByText(/pick a column/).first().click({ timeout: 8000 }).catch((e) => say("pick fail"));
  await page.waitForTimeout(800);
  say("COLS", await page.locator("[role^=menuitem],[role=option]").allInnerTexts());
  await page.locator("[role^=menuitem],[role=option]").filter({ hasText: /Owner note/ }).first().click();
  await page.waitForTimeout(800);
  say("CLAUSE", (await d.locator("[data-testid=stage-rule-clause-in-words]").allInnerTexts()).join(" / "));
  await d.getByLabel("What it says").fill("Write an owner note before a card can be Done.");
  await shot(`stage-${tag}-2`);
  const buttons = await d.getByRole("button").allInnerTexts();
  say("BTNS", buttons.filter((b) => /Save|Add|Done|Cancel|Rule/i.test(b)));
  await d.getByRole("button", { name: /^(Save|Add this rule|Add rule)/ }).first().click().catch((e) => say("no save", e.message.slice(0, 80)));
  await page.waitForTimeout(5000);
  say("AFTER", (await d.innerText()).replace(/\n+/g, " | ").match(/Rules for entering a stage.{0,500}/)?.[0]);
  await shot(`stage-${tag}-3`);
}
await browser.close();
