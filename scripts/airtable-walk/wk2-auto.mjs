import { live, gotoTable, openAutomations, say } from "./ba-lib.mjs";
const tid = process.env.TID;
const { browser, page, shot } = await live(false);
await gotoTable(page, tid);
await openAutomations(page);
await shot("wk2-auto-1");
const dlg = page.locator("[role=dialog]").last();
say("DLG", (await dlg.innerText()).replace(/\n+/g," | ").slice(0,800));
say("BTN", (await dlg.getByRole("button").allInnerTexts()).filter(Boolean));
await dlg.getByRole("button",{name:"New automation"}).click();
await page.waitForTimeout(3000);
await shot("wk2-auto-2");
say("DLG2", (await dlg.innerText()).replace(/\n+/g," | ").slice(0,1200));
say("BTN2", (await dlg.getByRole("button").allInnerTexts()).filter(Boolean));
await dlg.getByPlaceholder("Automation name").fill("WK2- Asana who am I");
await dlg.getByRole("button",{name:"Use a connected app"}).click();
await page.waitForTimeout(2500);
await shot("wk2-auto-3");
say("STEP", (await dlg.innerText()).replace(/\n+/g," | ").match(/Do.{0,900}/)?.[0]);
say("CTRL", await dlg.locator("[role=combobox],input,select,button").evaluateAll(e=>e.filter(x=>x.offsetParent).map(x=>(x.getAttribute("aria-label")||x.placeholder||x.innerText||"").slice(0,30)).slice(-25)));
const opts=()=>page.locator("[role=option],[role^=menuitem]");
await page.mouse.click(790,593); await page.waitForTimeout(1200);
say("O1", (await opts().allInnerTexts()).slice(0,60).join(","));
await opts().filter({hasText:/asana/i}).first().click(); await page.waitForTimeout(4000);
await shot("wk2-auto-4");
say("AFTER1", (await dlg.innerText()).replace(/\n+/g," | ").match(/Step 1.{0,400}/)?.[0]);
await page.mouse.click(790,608); await page.waitForTimeout(1500);
await opts().filter({hasText:/^get me$/i}).first().click(); await page.waitForTimeout(2000);
await shot("wk2-auto-5");
say("AFTER2", (await dlg.innerText()).replace(/\n+/g," | ").match(/Step 1.{0,300}/)?.[0]);
await dlg.getByRole("button",{name:"Create"}).click(); await page.waitForTimeout(5000);
await shot("wk2-auto-6");
say("CREATED", (await dlg.innerText()).replace(/\n+/g," | ").slice(0,700));
process.exit(0);