import { start, open, ORIGIN } from "./lib.mjs";
import { mkdirSync } from "node:fs";
const D = process.env.D; const T = process.argv[2];
const { browser, page, who, errs } = await start(false);
console.log("who", who);
await open(page, T);
await page.screenshot({ path: `${D}/ex-01-table.png` });
const labs = async (sel) => (await page.locator(sel).evaluateAll((els) => els.map((e) => (e.getAttribute("aria-label") || e.innerText || e.title || "").replace(/\s+/g, " ").trim().slice(0, 60)))).filter(Boolean);
console.log("TOOLBAR buttons:", JSON.stringify(await labs("[data-table-toolbar] button")));
console.log("ALL buttons:", JSON.stringify(await labs("button")).slice(0, 2500));
const cell = page.locator("[data-matrx-cell-col='item']").first();
await cell.click({ button: "right" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${D}/ex-02-rowmenu.png` });
console.log("MENU items:", JSON.stringify(await labs("[role=menuitem], [role=menu] button, [data-context-menu] *")).slice(0, 2000));
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Table menu" }).click().catch((e) => console.log("no table menu", e.message.split("\n")[0]));
await page.waitForTimeout(1000);
await page.screenshot({ path: `${D}/ex-03-tablemenu.png` });
console.log("TABLEMENU:", JSON.stringify(await labs("[role=menuitem], [role=menu] *")).slice(0, 2500));
console.log("errs", JSON.stringify(errs.slice(0, 5)));
await browser.close();
