import { boot, goto, labs, D } from "./at-walk-a-lib.mjs";
const T = process.argv[2];
const { browser, page, who, errs } = await boot();
console.log("who", who);
await goto(page, "/data/" + T, "[data-table-toolbar]");
await page.screenshot({ path: `${D}/ex-01-table.png` });
console.log("ALL buttons:", JSON.stringify(await labs(page, "button")).slice(0, 2500));
await page.waitForSelector("[data-matrx-cell-col]", { timeout: 150000 }).catch(async () => { await page.screenshot({ path: `${D}/ex-nocells.png` }); console.log("NOCELLS body:", (await page.locator("body").innerText()).replace(/\s+/g, " ").slice(-1500)); });
console.log("cols", JSON.stringify(await page.locator("[data-matrx-cell-col]").evaluateAll((e) => [...new Set(e.map((x) => x.getAttribute("data-matrx-cell-col")))])));
await page.locator("[data-matrx-cell-col]").first().click({ button: "right" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${D}/ex-02-rowmenu.png` });
console.log("MENU items:", JSON.stringify(await labs(page, "[role=menuitem]")).slice(0, 2000));
await page.keyboard.press("Escape");
await page.getByRole("button", { name: "Table menu" }).click().catch((e) => console.log("no table menu", e.message.split("\n")[0]));
await page.waitForTimeout(1000);
await page.screenshot({ path: `${D}/ex-03-tablemenu.png` });
console.log("TABLEMENU:", JSON.stringify(await labs(page, "[role=menuitem]")).slice(0, 2500));
console.log("errs", JSON.stringify(errs.slice(0, 5)));
await browser.close();
