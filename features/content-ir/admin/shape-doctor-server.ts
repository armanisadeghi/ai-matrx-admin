function readSource(relPath: string): string | null {
  try {
    return readFileSync(
      join(/* turbopackIgnore: true */ process.cwd(), relPath),
      "utf8",
    );
  } catch {
    return null;
  }
}

interface CodeInputs {
  detectorTokens: DoctorDetectorToken[];
  /** Host detection-token surface for the registry↔host reconciliation;
   * null when the sources are unreadable (finding omitted, warned). */
  hostSurfaceTokens: HostSurfaceTokens | null;
  compiledKinds: string[];
  artifactKinds: string[];
  /** Block types resolveBlockDispatch answers; null when block-dispatch.tsx is
   * unreadable here (the dangling-component-key check goes quiet, loudly). */
  dispatchKeys: string[] | null;
  /** Compiled per-kind loadingComponent declarations (system-kinds + kinds/*).
   * Empty when sources are unreadable — the Loading column then under-reports
   * for compiled kinds and leaves the drift diff. */
  compiledLoadingSlugs: Map<string, string>;
  /** Columns whose live value depends on unavailable sources — excluded from
   * the snapshot diff so degraded runtimes never report fake drift. */
  excludedFromDrift: AssetColumn[];
  warnings: string[];
}

function gatherCodeInputs(): CodeInputs {
  const warnings: string[] = [];
  const excluded = new Set<AssetColumn>();

  const accumulatorText = readSource(SOURCE_FILES.accumulator);
  const splitterText = readSource(SOURCE_FILES.splitter);
  let detectorTokens: DoctorDetectorToken[] = [];
  let hostSurfaceTokens: HostSurfaceTokens | null = null;
  if (accumulatorText && splitterText) {
    const { tokens, failures } = extractDetectorTokensFromTexts({
      accumulatorText,
      splitterText,
    });
    detectorTokens = tokens;
    const hostExtraction = extractHostSurfaceTokensFromTexts({
      accumulatorText,
      splitterText,
    });
    hostSurfaceTokens = hostExtraction.tokens;
    failures.push(...hostExtraction.failures);
    // Both extractors report the same missing literal — say each one once.
    const missing = [...new Set(failures.map((f) => `${f.literal} in ${f.file}`))];
    for (const m of missing) {
      warnings.push(
        // access-errors: ok — admin shape-doctor census warning about source-code literals, developer-facing
        `The stream detector list ${m} could not be read, so the check for unregistered detector tags is not running.`,
      );
    }
  } else {
    warnings.push(
      "The stream detector sources could not be read here, so the check for unregistered detector tags is not running.",
    );
  }

  const systemKindsText = readSource(SOURCE_FILES.systemKinds);
  const artifactText = readSource(SOURCE_FILES.artifactRegistry);
  let compiledKinds: string[] = [];
  let artifactKinds: string[] = [];
  if (systemKindsText) {
    compiledKinds = compiledKindSlugsFromText(systemKindsText);
  }
  if (artifactText) {
    artifactKinds = artifactKindSlugsFromText(artifactText);
  }
  if (!systemKindsText || !artifactText) {
    excluded.add("component");
    warnings.push(
      "The built-in component lists could not be read here, so the Component column may under-report.",
    );
  }

  // Compiled loadingComponent declarations — system-kinds.ts plus every
  // kinds/*.ts module it imports. Loud-degrade like the rest: unreadable
  // sources exclude the Loading column from the drift diff.
  let compiledLoadingSlugs = new Map<string, string>();
  try {
    const kindsDir = join(/* turbopackIgnore: true */ process.cwd(), SOURCE_FILES.kindsDir);
    const kindTexts = readdirSync(kindsDir)
      .filter((name) => name.endsWith(".ts"))
      .map((name) => readFileSync(join(kindsDir, name), "utf8"));
    compiledLoadingSlugs = compiledLoadingSlugsFromTexts([
      ...(systemKindsText ? [systemKindsText] : []),
      ...kindTexts,
    ]);
    if (!systemKindsText) excluded.add("loading");
  } catch {
    excluded.add("loading");
    warnings.push(
      "The built-in loading components could not be read here, so the Loading column may under-report.",
    );
  }

  // Dispatch keys — the code side of the dangling-component_key red. Unreadable
  // (or an extraction failure) means the check CANNOT run: it is skipped and
  // the Component column leaves the drift diff, never silently passed.
  const dispatchSources = DISPATCH_SOURCE_KEYS.map((key) => {
    const file = SHAPE_SOURCE_FILES[key].path;
    return { file, text: readSource(file) };
  });
  let dispatchKeys: string[] | null = null;
  if (dispatchSources.every((s) => s.text !== null)) {
    const extraction = extractDispatchKeysFromTexts(
      dispatchSources.map((s) => ({ file: s.file, text: s.text ?? "" })),
      { DB_KIND_COMPONENT_KEY, GENERIC_STRUCTURED_COMPONENT_KEY },
    );
    if (extraction.failures.length === 0) {
      dispatchKeys = extraction.keys;
    } else {
      warnings.push(
        // access-errors: ok — admin shape-doctor census warning about source-code literals, developer-facing
        `Dispatch table literal(s) ${extraction.failures.map((f) => `${f.literal} (${f.file})`).join(", ")} not found, so the check for components pointing at nothing is not running.`,
      );
    }
  } else {
    warnings.push(
      `${dispatchSources.filter((s) => s.text === null).map((s) => s.file).join(", ")} could not be read here, so the check for components pointing at nothing is not running.`,
    );
  }
  if (!dispatchKeys) excluded.add("component");

  return {
    detectorTokens,
    hostSurfaceTokens,
    compiledKinds,
    artifactKinds,
    dispatchKeys,
    compiledLoadingSlugs,
    excludedFromDrift: [...excluded],
    warnings,
  };
}

