// features/shell/breadcrumbs/pageless-levels.ts
//
// EVERY CRUMB IS A REAL DOOR (Arman, 2026-10-22: "I don't want fake things!!"). A breadcrumb level
// is one address segment; some addresses have NO page of their own (`/marketing/brands/smart-add/validate`
// only exists as the parent of `/validate/<brandId>`). A crumb linking there is a 404; a crumb drawn
// as plain text there is a dead end. Neither is allowed: the derivation drops such a level and the
// next level carries on (deriveTrail).
//
// The truth comes from the route manifest (lib/route-manifest/manifest.generated.json — every page
// the app serves). `pagelessLevelsOf` turns its patterns into a small table (~170 addresses, a few
// KB) written to `pageless-levels.generated.ts` by `pnpm route-manifest:generate`; the browser never
// loads the manifest itself. Test `__tests__/every-crumb-is-a-door.test.ts` fails when they disagree.
//
// A level next.config.js REDIRECTS (`/marketing/brands/smart-add` → `…/company`) is a real door:
// the generator passes `redirectedPatternsOf(next.config.js)` (redirect-levels.ts) as `redirected`.
//
// Next.js matches a static folder before a dynamic one, so a pageless `[param]` level never swallows
// a static sibling with a page: `staticNames` lists, per parent, the static names that shadow it.

export interface PagelessTable {
  /** Address patterns (`[param]` = any one segment) that are a folder with no page of their own. */
  levels: readonly string[];
  /** Parent pattern → the static child names beside a pageless `[param]` child (they win the match). */
  staticNames: Readonly<Record<string, readonly string[]>>;
}

const isDynamic = (seg: string) => seg.startsWith("[");
const isCatchAll = (seg: string) => seg.startsWith("[...") || seg.startsWith("[[...");

/**
 * The pageless levels of a set of page patterns (every proper prefix that answers no page). An
 * address a next.config redirect sends on (`redirected`, from redirect-levels.ts) answers: the crumb
 * lands on a real page, so it stays a link.
 */
export function pagelessLevelsOf(patterns: readonly string[], redirected: readonly string[] = []): PagelessTable {
  const dyn = (p: string) => p.replace(/\[[^\]]+\]/g, "[]");
  const pages = new Set([...patterns, ...redirected].map(dyn));
  // A folder answers when it has a page, or an OPTIONAL catch-all child (matches zero segments).
  const optionalCatchAllParents = new Set(
    patterns.filter((p) => /\/\[\[\.\.\.[^\]]+\]\]$/.test(p)).map((p) => p.replace(/\/\[\[\.\.\.[^\]]+\]\]$/, "") || "/"),
  );
  const answers = (prefix: string) => pages.has(dyn(prefix)) || optionalCatchAllParents.has(prefix);
  const childNames = new Map<string, Set<string>>();
  const levels = new Set<string>();
  for (const pattern of patterns) {
    const segs = pattern.split("/").filter(Boolean);
    for (let i = 0; i < segs.length; i++) {
      const parent = `/${segs.slice(0, i).join("/")}`;
      if (!childNames.has(parent)) childNames.set(parent, new Set());
      childNames.get(parent)!.add(segs[i]!);
    }
    for (let i = 1; i < segs.length; i++) {
      if (isCatchAll(segs[i - 1]!)) break;
      const prefix = `/${segs.slice(0, i).join("/")}`;
      if (!answers(prefix)) levels.add(prefix);
    }
  }
  const staticNames: Record<string, string[]> = {};
  for (const level of levels) {
    const segs = level.split("/").filter(Boolean);
    segs.forEach((seg, i) => {
      if (!isDynamic(seg)) return;
      const parent = `/${segs.slice(0, i).join("/")}`;
      const names = [...(childNames.get(parent) ?? [])].filter((n) => !isDynamic(n)).sort();
      if (names.length > 0) staticNames[parent] = names;
    });
  }
  return {
    levels: [...levels].sort(),
    staticNames: Object.fromEntries(Object.entries(staticNames).sort(([a], [b]) => a.localeCompare(b))),
  };
}

/** Is this concrete address a folder with no page of its own? */
export function isPagelessLevel(href: string, table: PagelessTable): boolean {
  const segs = (href.split(/[?#]/, 1)[0] ?? "").split("/").filter(Boolean);
  return table.levels.some((level) => {
    const pat = level.split("/").filter(Boolean);
    if (pat.length !== segs.length) return false;
    return pat.every((p, i) => {
      if (!isDynamic(p)) return p === segs[i];
      // A static sibling folder wins Next's match: this dynamic level is not the one answering.
      const parent = `/${pat.slice(0, i).join("/")}`;
      return !(table.staticNames[parent] ?? []).includes(segs[i]!);
    });
  });
}

/** The generated file's source text (pnpm route-manifest:generate writes it). */
export function renderPagelessLevelsModule(table: PagelessTable): string {
  return [
    "// GENERATED by `pnpm route-manifest:generate` from lib/route-manifest/manifest.generated.json — never edit.",
    "// Address levels with no page of their own; a breadcrumb never links to one (pageless-levels.ts).",
    'import type { PagelessTable } from "./pageless-levels";',
    "",
    `export const PAGELESS_LEVELS: PagelessTable = ${JSON.stringify(table, null, 2)};`,
    "",
  ].join("\n");
}
