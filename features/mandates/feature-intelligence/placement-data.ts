// features/mandates/feature-intelligence/placement-data.ts
//
// THE TWO READS every Intelligence page arranges (`placement-model.ts`):
//   • the registry tree — `platform.taxonomy_node` (every signed-in person reads all of it)
//   • where each visible job sits — `mandate.intelligence_placement` (SECURITY INVOKER:
//     RLS decides the rows), plus which of those rows are shortcuts
//     (`mandate.vw_shortcut`), so a shortcut offered everywhere reads as Everywhere.
// Both take the caller's client, so the server routes (the `?mandate=` redirect)
// and the browser pages read the same way.

import type { SupabaseClient } from "@supabase/supabase-js";
import { readAllRows } from "@ai-matrx/data/db";
import type { Database } from "@/types/database.types";
import {
  placementFromWire,
  type PlacementRow,
  type TaxonomyNode,
} from "./placement-model";

type Db = SupabaseClient<Database>;

export async function readTaxonomyNodes(client: Db): Promise<TaxonomyNode[]> {
  return readAllRows(
    ({ from, to }) =>
      client
        .schema("platform")
        .from("taxonomy_node")
        .select("id, slug, name, parent_id, status", { count: "exact" })
        .order("id", { ascending: true })
        .range(from, to)
        .returns<TaxonomyNode[]>(),
    { label: "platform.taxonomy_node (intelligence tree)" },
  );
}

/**
 * Where each visible job sits. `keys` narrows to exact keys (null = every job
 * the viewer can see).
 */
export async function readPlacement(
  client: Db,
  keys: readonly string[] | null = null,
): Promise<PlacementRow[]> {
  // MATRX-EXCEPTION: `mandate.intelligence_placement` is not in the generated
  // types yet (types/database.types.ts is regenerated by its own lane); every
  // row is runtime-checked by `placementFromWire` instead.
  const raw = await readAllRows<unknown>(
    ({ from, to }) =>
      client
        .schema("mandate")
        .rpc(
          "intelligence_placement" as never,
          { p_keys: keys ? [...keys] : null } as never,
          { count: "exact" },
        )
        .order("mandate_key" as never, { ascending: true })
        .range(from, to) as unknown as PromiseLike<{
        data: unknown[] | null;
        error: { message: string } | null;
        count?: number | null;
      }>,
    { label: "mandate.intelligence_placement" },
  );
  // Only a soft job no node holds needs the answer (Everywhere vs its owner lane).
  const ids = raw
    .map((row) => (row && typeof row === "object" ? (row as Record<string, unknown>) : null))
    .filter((row) => row !== null && row.placed_by === "none" && row.origin !== "code")
    .map((row) => row?.mandate_id)
    .filter((id): id is string => typeof id === "string");
  const shortcutIds = await readShortcutIds(client, ids);
  return raw
    .map((row) => placementFromWire(row, shortcutIds))
    .filter((row): row is PlacementRow => row !== null);
}

const ID_CHUNK = 150;

async function readShortcutIds(client: Db, ids: readonly string[]): Promise<Set<string>> {
  const out = new Set<string>();
  for (let start = 0; start < ids.length; start += ID_CHUNK) {
    const chunk = ids.slice(start, start + ID_CHUNK);
    const { data, error } = await client
      .schema("mandate")
      .from("vw_shortcut")
      .select("mandate_id")
      .is("deleted_at", null)
      .in("mandate_id", chunk);
    if (error) throw new Error(`mandate.vw_shortcut: ${error.message}`);
    for (const row of data ?? []) if (row.mandate_id) out.add(row.mandate_id);
  }
  return out;
}
