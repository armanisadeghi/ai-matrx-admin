/**
 * Drain the pending promise chain after a click, in macrotask TURNS.
 *
 * The three sites below waited a literal 5ms / 10ms, which is not a wait for the
 * work — it is a bet that 5 real milliseconds is longer than a Supabase-mock
 * round trip. Under the whole battery's 40 workers that bet loses: this suite
 * failed the 2026-09-19 whole-battery run reading `remote N+2` where it expects
 * `remote N+1` (one extra queued `from("notes")` had been consumed) and passed
 * on its own. Turns drain the same chain and do not care how loaded the machine
 * is.
 */
async function settle(turns = 6): Promise<void> {
  for (let i = 0; i < turns; i += 1) {
    await new Promise((resolve) => setTimeout(resolve, 0));
  }
}

