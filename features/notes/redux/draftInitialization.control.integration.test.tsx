/** An rpc mock whose promise is released (resolved or rejected) by the test. */
function deferredRpc(): { rpc: jest.Mock; settle: { resolve?: (value: unknown) => void; reject?: (reason?: unknown) => void } } {
  const settle: { resolve?: (value: unknown) => void; reject?: (reason?: unknown) => void } = {};
  const promise = new Promise((resolve, reject) => {
    settle.resolve = resolve;
    settle.reject = reject;
  });
  // Swallow nothing: the control under test owns this rejection.
  return { rpc: jest.fn().mockReturnValue(promise), settle };
}

