/**
 * Build the `matrx-user/notes` surface scope at trigger time.
 *
 * Returns a `() => SurfaceScopePayload` builder rather than a static object,
 * because the textarea's selection lives in the DOM (not React state) and the
 * caller wants the *current* selection at the moment the user clicks an
 * action — not a stale snapshot from the last render.
 *
 * Workspace-wide state (note metadata, home tree, tab summaries, scope
 * assignments, find/replace) is read from the store at call time via
 * `store.getState()` — NOT via subscriptions — so the returned builder stays
 * referentially stable across unrelated store churn (the 2026-07 keystroke
 * freeze class: a builder that re-identifies per keystroke re-memoizes every
 * consumer downstream).
 *
 * Wire-up pattern (see `NoteContextMenuContent.executeDirective`):
 *
 *   const buildSurfaceScope = useNotesSurfaceScope({ ... });
 *   ...
 *   await trigger(shortcutId, {
 *     scope: buildSurfaceScope(),
 *     sourceFeature: "notes",
 *     runtime: { surfaceName: "matrx-user/notes" },
 *   });
 */

import { useNoteHomeNames } from "@/features/notes/homes/useNoteHomes";
import { useCallback, useEffect, useRef } from "react";
import { usePageGuidanceRecord } from "@/features/mandates/host-values/usePageGuidanceRecord";
import { provideHostValues, type HostValuesFor } from "@/features/mandates/host-values/host-values";
import { MANDATE_KEYS } from "@ai-matrx/agents/mandates";
import type { RefObject } from "react";

import { useAppSelector, useAppStore } from "@/lib/redux/hooks";
import { selectCanvasKindVisibility } from "@ai-matrx/canvas";
import { NOTE_HISTORY_KIND } from "@/features/notes/canvas/noteHistoryKind";
import type { SurfaceScopePayload } from "@ai-matrx/chat/surfaces/types";
import {
  selectFindReplaceState,
  selectInstanceSplitNoteId,
  selectInstanceTabs,
  selectNoteById,
  selectNoteIsAutogenerated,
  selectNoteIsDirtyById,
  selectNoteScopeAssignments,
  selectNotesMap,
} from "@/features/notes/redux/selectors";
import type { EditorMode } from "@/features/notes/components/NoteEditorCore";
import {
  buildNotesEditorContextData,
  type NotesEditorFindReplace,
  type NotesEditorNotesMapEntry,
  type NotesEditorSharedAccess,
} from "@/features/notes/agent-context/buildNotesEditorContextData";
import {
  selectCustomFieldsScopeValue,
  useCustomFieldsRead,
} from "@/features/unified-data/customFieldsRead";

export interface UseNotesSurfaceScopeParams {
  /**
   * NotesView instance id (per-pane state, owns tabs + split note). Optional
   * for callsites outside the multi-tab Notes view (overlays, embedded
   * editors); when absent the scope reports an empty tab list and no split.
   */
  instanceId?: string;
  /** Id of the note the user has open in the active tab. */
  noteId: string;
  /** Live note body — usually the in-flight buffer (`localContent`). */
  content: string;
  /** Reference to the editor textarea — selection is read live from the DOM. */
  textareaRef: RefObject<HTMLTextAreaElement | null>;
  /** Active note's editor mode (write / plain / source / preview). */
  editorMode: EditorMode;
}

/**
 * Returns a stable function that snapshots the Notes surface state and emits a
 * `SurfaceScopePayload` for `matrx-user/notes`. The function is stable across
 * renders for a given (instanceId, noteId) — the live values are pulled from
 * Redux + the textarea DOM at call time.
 */
/** The `notes.page_guidance` offered values this surface holds — sent on the
 * Notes guide's first turn (audit F-7: it rendered `I have the note "" open`). */
const NOTES_GUIDE_VALUES = [
  "text_before", "text_after", "current_note_id", "current_note_title", "content",
  "current_note_home", "current_note_tags", "current_note_shown_to",
  "current_note_published_to_web", "current_note_word_count", "current_note_updated_at",
  "current_note_is_dirty", "is_new_note", "current_heading", "current_section_text",
  "cursor_offset", "editor_mode", "open_note_ids", "open_notes_summary", "split_note_id",
  "history_pane_open", "all_homes", "current_home_note_ids", "note_scope_assignments",
  "shared_access", "find_replace", "custom_fields",
] as const satisfies readonly (keyof HostValuesFor<"notes.page_guidance">)[];

export function useNotesSurfaceScope(
  params: UseNotesSurfaceScopeParams,
): () => SurfaceScopePayload {
  const { instanceId, noteId, content, textareaRef, editorMode } = params;

  // Empty-string sentinel for selectors when no instance is bound (overlay use).
  const instanceKey = instanceId ?? "";

  const store = useAppStore();
  const isDirty = useAppSelector(selectNoteIsDirtyById(noteId));
  const isAutogenerated = useAppSelector(selectNoteIsAutogenerated(noteId));
  const openTabs = useAppSelector(selectInstanceTabs(instanceKey));
  const splitNoteId = useAppSelector(selectInstanceSplitNoteId(instanceKey));
  // `custom_fields` is this provider's value: the note's real fields + values, read once per
  // record (the same keyed read the info panel's section uses), answered with the panel closed.
  const noteOrganizationId =
    useAppSelector((state) => (noteId ? selectNoteById(noteId)(state)?.organization_id : null)) ?? null;
  useCustomFieldsRead("note", noteId && !isAutogenerated ? noteId : null, noteOrganizationId);

  // The homes the notes live in, named by one specific read — the whole scope tree is not loaded
  // for an agent surface nobody has used (first-paint contract). `all_homes` lists those names.
  const homes = useNoteHomeNames();

  // The note in view, handed to the page guide's first turn (host-values channel).
  usePageGuidanceRecord(() => {
    if (!noteId) return null;
    const record = selectNoteById(noteId)(store.getState());
    return { id: noteId, type: "note", title: record?.label ?? null };
  });

  const buildScope = useCallback(() => {
    const ta = textareaRef.current;
    const text = ta?.value ?? content ?? "";
    const selectionStart = ta?.selectionStart ?? 0;
    const selectionEnd = ta?.selectionEnd ?? selectionStart;

    // Workspace-wide state, read at trigger time (not subscribed — see header).
    const state = store.getState();
    const record = noteId ? selectNoteById(noteId)(state) : undefined;
    // Homes, by the label the home tree shows.
    const allHomes = homes.homes.map((home) => homes.labelOf(home.scopeId) ?? home.name);
    // Project the store's NoteRecords down to the builder's lightweight map
    // entries (deleted_at → is_deleted so deleted notes never count as
    // home peers).
    const notesMap: Record<string, NotesEditorNotesMapEntry> = {};
    for (const [id, rec] of Object.entries(selectNotesMap(state))) {
      notesMap[id] = {
        id,
        label: rec.label,
        home_label: homes.labelOf(rec.home_scope_id),
        updated_at: rec.updated_at,
        is_deleted: rec.deleted_at != null,
      };
    }
    const scopeAssignments = selectNoteScopeAssignments(state)
      .filter((a) => a.entity_id === noteId)
      .map((a) => ({
        scope_id: a.scope_id,
        scope_name: a.scope_name,
        scope_type: a.scope_type,
      }));
    // The note's version history is its canvas tab; "open" = in front.
    // (A store mounted without the canvas has no tab to be in front.)
    const canvasHost = state.canvasHost as typeof state.canvasHost | undefined;
    const historyOpen = canvasHost
      ? selectCanvasKindVisibility(canvasHost, NOTE_HISTORY_KIND, noteId) === "visible"
      : false;
    const fr = selectFindReplaceState(instanceKey)(state);
    const findReplace: NotesEditorFindReplace | null =
      fr && fr.isOpen
        ? {
            query: fr.query,
            scope: fr.scope,
            case_sensitive: fr.caseSensitive,
            use_regex: fr.useRegex,
            match_count: fr.matchCount,
          }
        : null;
    const sharedAccess: NotesEditorSharedAccess | null =
      record?._sharedWithMe && record._sharedMeta
        ? {
            permission_level: record._sharedMeta.permissionLevel,
            owner_email: record._sharedMeta.ownerEmail,
          }
        : null;

    return buildNotesEditorContextData({
      noteId,
      content: text,
      selectionStart,
      selectionEnd,
      editorMode,
      noteRecord: record
        ? {
            label: record.label,
            home_label: homes.labelOf(record.home_scope_id),
            tags: record.tags,
            shown_to: record.shown_to,
            published_to_web: record.published_to_web,
            updated_at: record.updated_at,
          }
        : null,
      isDirty,
      isAutogenerated,
      openTabs: openTabs ?? [],
      splitNoteId,
      allHomes,
      notesMap,
      sharedAccess,
      scopeAssignments,
      historyOpen,
      findReplace,
      customFields: selectCustomFieldsScopeValue(
        state,
        "note",
        noteId && !isAutogenerated ? noteId : null,
        record?.organization_id ?? null,
      ),
    }) as SurfaceScopePayload;
  }, [
    homes,
    store,
    textareaRef,
    content,
    noteId,
    instanceKey,
    editorMode,
    isDirty,
    isAutogenerated,
    openTabs,
    splitNoteId,
  ]);

  // The Notes guide reads the open note by name; it is read at submit time.
  // The builder re-identifies as the body changes, so the provider reads it
  // through a ref and registers once per note (no per-keystroke churn).
  const latestBuild = useRef(buildScope);
  useEffect(() => {
    latestBuild.current = buildScope;
  });
  useEffect(() => {
    if (!noteId) return undefined;
    return provideHostValues(MANDATE_KEYS.notes__page_guidance, "notes.page_guidance", () => {
      const scope = latestBuild.current() as Record<string, unknown>;
      return Object.fromEntries(
        NOTES_GUIDE_VALUES.map((name) => [name, scope[name]]),
      ) as HostValuesFor<"notes.page_guidance">;
    });
  }, [noteId]);

  return buildScope;
}
