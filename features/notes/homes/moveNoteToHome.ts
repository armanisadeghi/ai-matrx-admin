// features/notes/homes/moveNoteToHome.ts
//
// THE ONE MOVE PATH for a note (item homes). Every move entry point — sidebar
// drag and drop, every "Move to…" menu, the bulk bar, the home chip, mobile,
// the agent write target — dispatches this thunk and nothing else.
//
// It calls `platform.set_home` with the note's current version, AWAITS the
// receipt, and only then writes home / organization / version into Redux.
// Nothing is optimistic: a refusal leaves the note exactly where it was and
// says the database's own reason.

import { createAsyncThunk } from "@reduxjs/toolkit";
import { supabase } from "@/utils/supabase/client";
import { toast } from "@/lib/toast";
import type { RootState } from "@/lib/redux/store";
import { applyNoteHomeReceipt } from "../redux/slice";
import { saveNote } from "../redux/thunks";
import type { NoteRecord } from "../redux/notes.types";
import { homeReceiptFrom, homeRefusalMessage, type HomeReceipt } from "./homeModel";

export type MoveNoteToHomeResult =
  | { ok: true; receipt: HomeReceipt }
  | { ok: false; message: string };

export interface MoveNoteToHomeArgs {
  noteId: string;
  scopeId: string;
  /** The home's display name, for "Moved to <home>". */
  homeLabel: string;
  /** Bulk moves say one summary themselves. */
  quiet?: boolean;
}

export const moveNoteToHome = createAsyncThunk<MoveNoteToHomeResult, MoveNoteToHomeArgs>(
  "notes/moveNoteToHome",
  async ({ noteId, scopeId, homeLabel, quiet }, { dispatch, getState }) => {
    const refuse = (message: string): MoveNoteToHomeResult => {
      if (!quiet) toast.error(message);
      return { ok: false, message };
    };
    const before = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
    if (!before) return refuse("This note is not open here. Reload and try again.");
    if (before.home_scope_id === scopeId) {
      return {
        ok: true,
        receipt: {
          homeScopeId: scopeId,
          organizationId: before.organization_id,
          organizationChanged: false,
          version: before.version,
          keptFields: [],
          unchanged: true,
        },
      };
    }

    // A note with unsaved edits (or a draft not stored yet) is written first, so
    // the move runs on the version the person is looking at.
    if (before._dirty || before._isAutogenerated) {
      try {
        await dispatch(saveNote(noteId)).unwrap();
      } catch (error) {
        return refuse(error instanceof Error ? error.message : "Save the note, then move it.");
      }
    }
    const current = (getState() as RootState).notes.notes[noteId] as NoteRecord | undefined;
    if (!current) return refuse("This note is not open here. Reload and try again.");

    const { data, error } = await supabase.schema("platform").rpc("set_home", {
      p_entity_type: "note",
      p_entity_id: noteId,
      p_scope_id: scopeId,
      p_expected_version: current.version,
    });
    if (error) return refuse(homeRefusalMessage(error));

    let receipt: HomeReceipt;
    try {
      receipt = homeReceiptFrom(data);
    } catch (malformed) {
      return refuse((malformed as Error).message);
    }

    dispatch(
      applyNoteHomeReceipt({
        id: noteId,
        homeScopeId: receipt.homeScopeId,
        organizationId: receipt.organizationId,
        version: receipt.version,
      }),
    );
    if (!quiet) {
      toast.success(
        receipt.keptFields.length > 0
          ? `Moved to ${homeLabel} · kept ${receipt.keptFields.join(", ")}`
          : `Moved to ${homeLabel}`,
      );
    }
    return { ok: true, receipt };
  },
);

/** Move several notes (any mix of organizations); one summary for the whole set. */
export const moveNotesToHome = createAsyncThunk<
  { moved: number; refused: { noteId: string; message: string }[] },
  { noteIds: readonly string[]; scopeId: string; homeLabel: string }
>("notes/moveNotesToHome", async ({ noteIds, scopeId, homeLabel }, { dispatch }) => {
  const refused: { noteId: string; message: string }[] = [];
  let moved = 0;
  for (const noteId of noteIds) {
    const result = await dispatch(moveNoteToHome({ noteId, scopeId, homeLabel, quiet: true })).unwrap();
    if (result.ok) moved += 1;
    else refused.push({ noteId, message: result.message });
  }
  if (refused.length === 0) {
    toast.success(`Moved ${moved} ${moved === 1 ? "note" : "notes"} to ${homeLabel}`);
  } else {
    toast.error(`Moved ${moved} of ${noteIds.length} to ${homeLabel}. ${refused[0].message}`);
  }
  return { moved, refused };
});
