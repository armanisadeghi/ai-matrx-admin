"use client";

// HomeQuickPick — the empty-state landing for every notes surface (/notes and
// the floating notes window). "New note" (the active organization's General —
// the database files it there) + the person's recent homes (a new note in
// that home) + recent notes. Never asks for an organization.

import { useCallback } from "react";
import { Box, FileText, House, Plus } from "lucide-react";
import { ErrorNotice } from "@ai-matrx/design-system";
import { useAppDispatch, useAppSelector } from "@/lib/redux/hooks";
import { ensureOrgId } from "@/lib/organizations/ensureOrgId";
import { cn } from "@/lib/utils";
import { addInstanceTab, setInstanceActiveTab } from "../redux/slice";
import { selectAllNotesList } from "../redux/selectors";
import { initializeAutogeneratedNote } from "../redux/thunks";
import { useDraftInitializationControl } from "../hooks/useDraftInitializationControl";
import type { ItemHome } from "@/features/scopes/homes/homeModel";
import { useNoteHomes } from "./useNoteHomes";

/** How many recent homes and recent notes the landing shows. */
const RECENT_LIMIT = 4;

export function HomeQuickPick({ instanceId, className }: { instanceId: string; className?: string }) {
  const dispatch = useAppDispatch();
  const allNotes = useAppSelector(selectAllNotesList);
  const userId = useAppSelector((s) => s.userAuth?.id);
  const homes = useNoteHomes();
  const draftControl = useDraftInitializationControl();

  const newNote = useCallback(
    (home?: ItemHome) =>
      draftControl.run(async () => {
        if (!userId) throw new Error("Sign in before starting a new note.");
        const organizationId = home ? home.organizationId : await ensureOrgId(null);
        await dispatch(
          initializeAutogeneratedNote({
            id: crypto.randomUUID(),
            userId,
            organizationId,
            instanceId,
            ...(home && !home.isGeneral ? { homeScopeId: home.scopeId } : {}),
          }),
        ).unwrap();
      }),
    [dispatch, userId, instanceId, draftControl],
  );

  const openNote = useCallback(
    (noteId: string) => {
      dispatch(addInstanceTab({ instanceId, noteId }));
      dispatch(setInstanceActiveTab({ instanceId, noteId }));
    },
    [dispatch, instanceId],
  );

  const byRecency = [...allNotes].sort((a, b) => (b.updated_at ?? "").localeCompare(a.updated_at ?? ""));
  const recentNotes = byRecency.slice(0, RECENT_LIMIT);
  const recentHomes: ItemHome[] = [];
  for (const note of byRecency) {
    const home = note.home_scope_id ? homes.byId.get(note.home_scope_id) : undefined;
    if (home && !recentHomes.some((h) => h.scopeId === home.scopeId)) recentHomes.push(home);
    if (recentHomes.length >= RECENT_LIMIT) break;
  }

  const tile =
    "flex flex-col items-center justify-center gap-2 py-4 rounded-xl border border-border bg-card hover:bg-accent hover:border-primary/30 transition-all group";

  return (
    <div className={cn("flex-1 flex flex-col px-4 py-6 overflow-auto gap-4", className)}>
      {draftControl.error && (
        <ErrorNotice size="inline" className="text-xs text-center" message={draftControl.error} />
      )}
      <div className="grid grid-cols-5 gap-2 w-full">
        <button
          type="button"
          className={cn(tile, "border-primary/40 bg-primary/5")}
          onClick={() => void newNote().catch(() => undefined)}
          disabled={draftControl.pending}
          title="New note"
          data-home-quick-pick="new"
        >
          <Plus className="w-5 h-5 shrink-0 text-primary" />
          <span className="text-[0.7rem] font-medium text-foreground leading-tight">New note</span>
        </button>
        {recentHomes.map((home) => {
          const label = homes.labelOf(home.scopeId) ?? home.name;
          const Icon = home.isGeneral ? House : Box;
          return (
            <button
              key={home.scopeId}
              type="button"
              className={tile}
              onClick={() => void newNote(home).catch(() => undefined)}
              disabled={draftControl.pending}
              title={`New note in ${label}`}
            >
              <Icon className="w-5 h-5 shrink-0 text-muted-foreground group-hover:text-foreground" />
              <span className="w-full truncate px-1 text-center text-[0.7rem] font-medium text-muted-foreground group-hover:text-foreground leading-tight">
                {label}
              </span>
            </button>
          );
        })}
      </div>

      {recentNotes.length > 0 && (
        <div className="flex flex-col gap-2">
          <p className="text-[0.65rem] font-medium uppercase tracking-wide text-muted-foreground/70 shrink-0">
            Recent notes
          </p>
          <div className="grid grid-cols-4 gap-2 w-full">
            {recentNotes.map((note) => {
              const title = note.label?.trim() || "Untitled";
              return (
                <button
                  key={note.id}
                  type="button"
                  className="flex flex-col items-start gap-1 px-3 py-3 rounded-xl border border-border bg-card hover:bg-accent hover:border-primary/30 transition-all group text-left min-w-0"
                  onClick={() => openNote(note.id)}
                  title={`Open ${title}`}
                >
                  <div className="flex items-center gap-1.5 w-full min-w-0">
                    <FileText className="w-3.5 h-3.5 shrink-0 text-muted-foreground" />
                    <span className="text-[0.7rem] font-medium text-foreground truncate flex-1 min-w-0">{title}</span>
                  </div>
                  <span className="text-[0.6rem] text-muted-foreground/70 truncate w-full">
                    {homes.labelOf(note.home_scope_id) ?? ""}
                  </span>
                </button>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
}
