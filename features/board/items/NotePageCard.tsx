"use client";

/**
 * A NOTE IN PAGE LAYOUT reads as a card, never as the notes workspace: the note's words drawn through the
 * one markdown pipeline, at their natural height (the page scrolls, nothing inside does), with no toolbar,
 * no second "…" menu and no second title (a first line that repeats the tile's title is left out — the
 * tile's header already names it). A press on the words while the tile is open for work opens the REAL
 * notes editor in place (`NoteWorkspace`, so saving, history and the agent surface stay the notes
 * feature's); Done returns to the card. The cover reads and edits the same way (`cover-items.tsx`).
 */

import { useEffect, useState } from "react";
import MarkdownStream from "@ai-matrx/chat/ui/markdown-stream/MarkdownStream";
import { Button } from "@ai-matrx/design-system/controls";
import { useAppDispatch, useAppSelector } from "@/lib/redux/hooks";
import { NoteWorkspace } from "@/features/notes/components/NoteWorkspace";
import { fetchNoteContent } from "@/features/notes/redux/thunks";
import { selectNoteById, selectNoteContent } from "@/features/notes/redux/selectors";
import { sameName } from "../engine/tile-chrome";

/** The words to read: a leading line (a heading or plain) that only repeats the title is dropped. */
export function noteCardText(content: string, title: string): string {
  const text = content.replace(/^\s+/, "");
  const nl = text.indexOf("\n");
  const first = (nl === -1 ? text : text.slice(0, nl)).replace(/^#{1,6}\s+/, "");
  if (!sameName(first, title)) return text;
  return nl === -1 ? "" : text.slice(nl + 1).replace(/^\s+/, "");
}

export function NotePageCard({
  noteId,
  instanceId,
  title,
  interacting,
}: {
  noteId: string;
  instanceId: string;
  title: string;
  interacting: boolean;
}) {
  const dispatch = useAppDispatch();
  const record = useAppSelector(selectNoteById(noteId));
  const content = useAppSelector(selectNoteContent(noteId)) ?? "";
  const loaded = record?._fetchStatus === "full" || record?._isAutogenerated === true;
  const [editing, setEditing] = useState(false);

  useEffect(() => {
    if (!loaded) void dispatch(fetchNoteContent(noteId));
  }, [dispatch, noteId, loaded]);

  if (editing) {
    return (
      <div data-board-note-editing="" className="flex h-[min(70dvh,640px)] flex-col bg-card">
        <div className="flex min-h-0 flex-1 flex-col">
          <NoteWorkspace instanceId={instanceId} noteId={noteId} title="host" />
        </div>
        <div className="flex shrink-0 justify-end border-t border-border px-3 py-2">
          <Button variant="primary" onClick={() => setEditing(false)}>
            Done
          </Button>
        </div>
      </div>
    );
  }

  if (!loaded) {
    return (
      <div className="flex flex-col gap-2 bg-card px-6 py-5" aria-busy="true" aria-label="Loading the note">
        <div className="h-3 w-full animate-pulse rounded bg-muted" />
        <div className="h-3 w-5/6 animate-pulse rounded bg-muted" />
      </div>
    );
  }

  const text = noteCardText(content, title);
  return (
    <article
      data-board-note-card=""
      onClick={() => {
        if (interacting) setEditing(true);
      }}
      className="bg-card px-6 py-5 text-[15px] leading-7"
    >
      {text.trim() ? (
        <MarkdownStream content={text} isStreamActive={false} />
      ) : (
        <p className="text-sm text-muted-foreground">Empty note</p>
      )}
    </article>
  );
}
