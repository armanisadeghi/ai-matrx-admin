/**
 * THE OVERLAY INDEX GENERATOR AND ITS GUARD (one file, so the two can never disagree).
 *
 * Adding an overlay is two files (<id>.overlay.ts(x) + <id>.render.tsx) plus one line in
 * registry.ts. Three files are derived from those and checked in:
 *   - overlay-definitions.gen.ts — one `export { xOverlay } from "./x.overlay"` per definition file
 *     (registry.ts imports it as a namespace, so registry.ts needs no import lines);
 *   - overlay-meta-index.ts — the plain id / label / instance / window identity of every overlay, in
 *     registry order, for code that must not load the "use client" definitions (server components);
 *   - render-map.ts — id → `() => import("./<id>.render")` by file name, imported ONLY by the overlay
 *     host (OverlayWorldHost, behind the app's lazy overlay-world boundary). Definitions carry no
 *     `render`: ~450 files import a definition to open it, and a `render` import() on each made every
 *     one of those graphs reach a window subtree (the host-build law; lab build OOM, 2026-10-17).
 *
 *   pnpm gen:overlays    rewrites all three (OVERLAY_INDEX_WRITE=1)
 *   pnpm check:overlays  fails when any is stale, a definition file is not in APP_OVERLAYS, a
 *                        definition has no <id>.render.tsx, or a definition declares its own `render`
 *
 * It runs under jest (not tsx) because loading the definitions needs the app's module mapping and
 * environment stubs, which jest already has.
 */
import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve(__dirname, "..");
const BARREL = path.join(DIR, "overlay-definitions.gen.ts");
const META = path.join(DIR, "overlay-meta-index.ts");
const RENDER_MAP = path.join(DIR, "render-map.ts");
const WRITE = process.env.OVERLAY_INDEX_WRITE === "1";
const STALE = "is stale: run `pnpm gen:overlays` and commit the result";

interface DefinitionFile {
  readonly file: string;
  readonly exportName: string;
}

/** Every <id>.overlay.ts(x), with its one `export const <name> = defineOverlay…`. Sorted, so deterministic. */
function scanDefinitionFiles(dir: string = DIR): DefinitionFile[] {
  return fs
    .readdirSync(dir)
    .filter((f) => /\.overlay\.tsx?$/.test(f))
    .sort()
    .map((file) => {
      const names = [...fs.readFileSync(path.join(dir, file), "utf8").matchAll(/^export const (\w+)\s*=\s*defineOverlay\b/gm)].map(
        (m) => m[1],
      );
      if (names.length !== 1) throw new Error(`${file}: expected exactly one \`export const <name> = defineOverlay\`, found ${names.length}`);
      return { file, exportName: names[0] };
    });
}

function barrelText(files: readonly DefinitionFile[]): string {
  const lines = files.map(({ file, exportName }) => `export { ${exportName} } from "./${file.replace(/\.tsx?$/, "")}";`);
  return `// GENERATED by \`pnpm gen:overlays\` from definitions/*.overlay.ts(x). Do not edit.\n/* eslint-disable no-barrel-files/no-barrel-files -- the one generated import list registry.ts reads */\n${lines.join("\n")}\n`;
}

interface MetaSource {
  readonly id: string;
  readonly label: string;
  readonly instance: string;
  readonly window?: { readonly windowId?: string; readonly mobile?: string; readonly deprecated?: { readonly replacement?: string; readonly reason?: string } };
}

const J = (v: unknown): string => JSON.stringify(v);

function metaIndexText(defs: readonly MetaSource[]): string {
  const rows = defs.map((d) => {
    let win = "";
    if (d.window) {
      const parts: string[] = [];
      if (d.window.windowId !== undefined) parts.push(`windowId: ${J(d.window.windowId)}`);
      if (d.window.mobile !== undefined) parts.push(`mobile: ${J(d.window.mobile)}`);
      const dep = d.window.deprecated;
      if (dep) {
        const depParts: string[] = [];
        if (dep.replacement !== undefined) depParts.push(`replacement: ${J(dep.replacement)}`);
        if (dep.reason !== undefined) depParts.push(`reason: ${J(dep.reason)}`);
        parts.push(`deprecated: { ${depParts.join(", ")} }`);
      }
      win = parts.length ? `, window: { ${parts.join(", ")} }` : ", window: {}";
    }
    return `  { id: ${J(d.id)}, label: ${J(d.label)}, instance: ${J(d.instance)}${win} },`;
  });
  return `/**
 * GENERATED by \`pnpm gen:overlays\` from the definitions in registry order. Do not edit.
 * Plain-data metadata for every app overlay, for code that must not load the "use client"
 * definitions (server components such as the feature admin lookups).
 */
import type { MobilePresentation } from "@ai-matrx/summon";

export interface OverlayMetaRow {
  readonly id: string;
  readonly label: string;
  readonly instance: "single" | "multi";
  readonly window?: {
    readonly windowId?: string;
    readonly mobile?: MobilePresentation;
    readonly deprecated?: { readonly replacement?: string; readonly reason?: string };
  };
}

export const OVERLAY_META_INDEX: readonly OverlayMetaRow[] = [
${rows.join("\n")}
];
`;
}

/** One `id: () => import("./id.render")` per definition file, sorted by file name. */
function renderMapText(files: readonly DefinitionFile[]): string {
  const rows = files.map(({ file }) => {
    const id = file.replace(/\.overlay\.tsx?$/, "");
    return `  ${id}: () => import(${J(`./${id}.render`)}),`;
  });
  return `/**
 * GENERATED by \`pnpm gen:overlays\` from definitions/*.overlay.ts(x) + *.render.tsx. Do not edit.
 * Every overlay's render module, by id. Imported ONLY by features/overlays/host/OverlayWorldHost.tsx
 * (behind the overlay world's one lazy edge): a definition file carries no import() edge, so the
 * ~450 files that import a definition to open it never reach a window subtree (host-build law).
 * check:import-fanout fails if anything else statically reaches this file.
 */
import type { OverlayRenderMap } from "@ai-matrx/summon/react";

export const RENDER_MAP: OverlayRenderMap = {
${rows.join("\n")}
};
`;
}

function readOrEmpty(file: string): string {
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
}

describe("overlay index (generated from the definitions)", () => {
  const files = scanDefinitionFiles();

  it("overlay-definitions.gen.ts exports every definition file", () => {
    const want = barrelText(files);
    if (WRITE) fs.writeFileSync(BARREL, want);
    if (readOrEmpty(BARREL) !== want) throw new Error(`overlay-definitions.gen.ts ${STALE}`);
  });

  it("every definition file is listed exactly once in APP_OVERLAYS (registry.ts)", () => {
    // Loaded after the barrel test so a write-mode run reads the barrel it just wrote.
    const { APP_OVERLAYS } = require("../registry") as typeof import("../registry");
    const listed = APP_OVERLAYS.map((d) => d.id);
    const defined = files.map((f) => f.file.replace(/\.overlay\.tsx?$/, ""));
    const missing = defined.filter((id) => !listed.includes(id as (typeof listed)[number]));
    const twice = listed.filter((id, i) => listed.indexOf(id) !== i);
    expect({ missingFromRegistry: missing, listedTwice: twice }).toEqual({ missingFromRegistry: [], listedTwice: [] });
  });

  it("render-map.ts has every definition's render module, and no definition declares its own render", () => {
    const noRenderFile = files.filter(({ file }) => !fs.existsSync(path.join(DIR, file.replace(/\.overlay\.tsx?$/, ".render.tsx"))));
    const ownRender = files.filter(({ file }) => /^\s*render\s*:/m.test(fs.readFileSync(path.join(DIR, file), "utf8")));
    expect({ noRenderFile: noRenderFile.map((f) => f.file), declaresOwnRender: ownRender.map((f) => f.file) }).toEqual({
      noRenderFile: [],
      declaresOwnRender: [],
    });
    const want = renderMapText(files);
    if (WRITE) fs.writeFileSync(RENDER_MAP, want);
    if (readOrEmpty(RENDER_MAP) !== want) throw new Error(`render-map.ts ${STALE}`);
  });

  it("overlay-meta-index.ts is the definitions' own metadata, row for row", () => {
    const { APP_OVERLAYS } = require("../registry") as typeof import("../registry");
    const want = metaIndexText(APP_OVERLAYS as unknown as readonly MetaSource[]);
    if (WRITE) fs.writeFileSync(META, want);
    if (readOrEmpty(META) !== want) throw new Error(`overlay-meta-index.ts ${STALE}`);
  });
});
